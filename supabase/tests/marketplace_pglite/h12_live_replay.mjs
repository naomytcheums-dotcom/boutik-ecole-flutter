  // ============================================================ A. Enregistrement (egress) : contrôles serveur
  const LR = await mkLive(HOST, 'Live en cours enregistre', { status: 'live' });
  for (const [who, fn] of [['anonyme', () => as(null)], ['hôte', () => as(HOST)], ['administrateur', () => as(ADM)]]) {
    await fn();
    await fails(`A1 ${who} : live_recording_start_check réservé au serveur`, `select live_recording_start_check('${LR}', '${HOST}')`, SERVICE_ONLY);
    await fails(`A2 ${who} : live_recording_egress_event réservé au serveur`, `select live_recording_egress_event('EG-X', 'complete', 'x/y.mp4', 10, null)`, SERVICE_ONLY);
    await fails(`A3 ${who} : claim / started / failed réservés au serveur`, `select live_recording_egress_claim('${RA.id}'), live_recording_egress_started('${RA.id}', 'EG-1'), live_recording_egress_failed('${RA.id}', 'x')`, SERVICE_ONLY);
    await fails(`A4 ${who} : replay_clip_mark / replay_transcript_store / declare_track réservés`, `select replay_clip_mark('${RA.id}', 'echec'), replay_transcript_store('${RA.id}', 'fr', '[]'::jsonb), live_recording_declare_track('${RA.id}', 'audio', 'a/b.mp4')`, SERVICE_ONLY);
  }
  let c = await srpc(`live_recording_start_check('${LR}', '${HOST}')`);
  check('A5 enregistreur non configuré : démarrage refusé (jamais simulé)', c.ok === false && c.reason === 'non_configure', JSON.stringify(c));
  await sup(); await db.exec(`update live_recording_config set enabled = true`);
  c = await srpc(`live_recording_start_check('${LR}', '${HOST}')`);
  check('A6 configuré mais l\'hôte n\'a pas demandé l\'enregistrement : refusé', c.ok === false && c.reason === 'enregistrement_non_demande', JSON.stringify(c));
  await sup(); await db.exec(`insert into live_cohosts (live_id, user_id, status) values ('${LR}', '${CO}', 'approved')`);
  await as(HOST);
  check('A7 l\'hôte demande l\'enregistrement', (await rpc(`live_recording_request('${LR}')`)) === 'en_attente');
  const rr = (await qs(`select id from live_recordings where live_id = '${LR}'`))[0].id;
  c = await srpc(`live_recording_start_check('${LR}', '${HOST}')`);
  check('A8 consentement du co-hôte manquant : démarrage refusé', c.ok === false && c.reason === 'consentement_manquant', JSON.stringify(c));
  c = await srpc(`live_recording_start_check('${LR}', '${V3}')`);
  check('A9 un tiers ne peut pas piloter l\'enregistrement', c.ok === false && c.reason === 'non_autorise');
  c = await srpc(`live_recording_start_check('${LR}', '${SUSP}')`);
  check('A9b un compte suspendu non plus', c.ok === false && c.reason === 'non_autorise');
  await as(CO); await rpc(`live_recording_consent('${LR}', true)`);
  c = await srpc(`live_recording_start_check('${LR}', '${CO}')`);
  check('A10 consentement donné : le co-hôte approuvé peut démarrer (check ok)', c.ok === true && c.recording_id === rr, JSON.stringify(c));
  check('A11 un seul démarrage : claim puis second claim refusé', (await srpc(`live_recording_egress_claim('${rr}')`)) === true && (await srpc(`live_recording_egress_claim('${rr}')`)) === false);
  await svc(); await fails('A12 identifiant d\'egress invalide refusé', `select live_recording_egress_started('${rr}', '  ')`, /invalide/);
  await srpc(`live_recording_egress_started('${rr}', 'EG-LR-1')`);
  c = await srpc(`live_recording_start_check('${LR}', '${HOST}')`);
