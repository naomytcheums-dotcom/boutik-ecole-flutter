  let hs = await rpc(`live_replay_host_state('${LR}')`);
  check('A14 état hôte : enregistrement en cours', hs.state === 'recording', JSON.stringify(hs));
  await as(V3);
  await fails('A15 un tiers ne lit pas l\'état d\'enregistrement du live', `select live_replay_host_state('${LR}')`, /non autorisée/);
  check('A16 mes replays : vide pour un tiers (isolation)', (await rpc(`my_replays()`)).length === 0);
  await as(HOST);
  check('A17 mes replays : le live de l\'hôte et son état', (await rpc(`my_replays()`)).some((x) => x.live_id === LR && x.replay.state === 'recording'));
