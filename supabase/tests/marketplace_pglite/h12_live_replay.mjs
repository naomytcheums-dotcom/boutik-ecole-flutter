  await sup(); await db.exec(`update replay_play_tickets set expires_at = now() - interval '1 minute'`);
  await as(V1);
  check('B7 ticket expiré : plus de lecture', (await q(`select count(*)::int n from storage.objects where bucket_id = 'live-replays'`))[0].n === 0);
  await fails('B8 membre : piste absente refusée (pas de piste « screen »)', `select replay_play_url('${RA.id}', 'screen')`, /piste n'est pas disponible/);
  await as(V2);
  await fails('B9 replay privé : non invité refusé', `select replay_play_url('${RB.id}')`, /privé/);
  await as(V3);
  await fails('B9b replay privé : playback refusé aussi', `select replay_playback_start('${RB.id}', 0)`, /privé/);
  await fails('B9c replay privé : progression, quiz, commentaires, notes refusés', `select replay_progress_get('${RB.id}')`, /privé/);
  await fails('B9d replay privé : commentaires illisibles', `select replay_comments_list('${RB.id}')`, /privé/);
  await as(V1);
  check('B10 replay privé : l\'invité y accède (accès hérité du live)', (await rpc(`replay_play_url('${RB.id}')`)).path === RB.path);
  await as(BAN);
  await fails('B11 banni du live : refusé', `select replay_play_url('${RA.id}')`, /pas accéder/);
  await as(SUSP);
  await fails('B12 compte suspendu : refusé', `select replay_play_url('${RA.id}')`, /suspendu/i);
  await as(V3);
  await fails('B13 live payant : sans billet refusé', `select replay_play_url('${RC.id}')`, /billet/);
  await as(V2);
  check('B14 live payant : le détenteur d\'un billet confirmé lit', (await rpc(`replay_play_url('${RC.id}')`)).path === RC.path);
  await as(V3);
  await fails('B15 replay masqué par l\'hôte : refusé aux autres', `select replay_play_url('${RD.id}')`, /pas publié/);
  await as(HOST);
  check('B16 replay masqué : l\'hôte y accède', (await rpc(`replay_play_url('${RD.id}')`)).path === RD.path);
  await as(ADM);
  check('B17 l\'administration y accède', (await rpc(`replay_play_url('${RD.id}')`)).path === RD.path);
  await as(V1);
  await fails('B18 enregistrement non prêt : refusé', `select replay_play_url('${RF.id}')`, /pas encore disponible/);
  await fails('B19 replay inconnu : refusé', `select replay_play_url('00000000-0000-0000-0000-00000000dead')`, /Accès refusé/);
  await as(V1);
  await sup(); await db.exec(`delete from storage.objects where bucket_id = 'live-replays' and name = '${RE.path}'`);
  await as(V1);
  await fails('B20 fichier absent du stockage : message honnête, pas de ticket', `select replay_play_url('${RE.id}')`, /introuvable sur le stockage/);
  await sup(); await db.exec(`insert into storage.objects (bucket_id, name) values ('live-replays', '${RE.path}')`);
  await as(V1);
  await fails('B21 lecture directe des tables refusée (progression, complétions, tickets, réglages)', `select count(*) from replay_settings`, DENY);
  await fails('B21b tickets non lisibles', `select count(*) from replay_play_tickets`, DENY);
  await fails('B21c commentaires non lisibles hors fonction', `select count(*) from replay_comments`, DENY);

  // ============================================================ C. Progression fiable : fraudes refusées
  const seq = { n: 0 };
  const ts = () => `(extract(epoch from clock_timestamp()) * 1000)::bigint + ${++seq.n}`;
  const arm = async (uid, rec, elapsed) => qs(`update replay_progress set session_at = clock_timestamp() - interval '${elapsed} seconds', win_start = null, win_count = 0 where user_id = '${uid}' and recording_id = '${rec}'`);
  const rep = async (uid, rec, from, to, elapsed = 25, tsq = null) => { if (elapsed !== null) await arm(uid, rec, elapsed); await as(uid); return rpc(`replay_progress_report('${rec}', ${from}, ${to}, ${tsq ?? ts()})`); };
  const start = async (uid, rec, pos = 0, elapsedSince = 10) => { await qs(`update replay_progress set session_at = clock_timestamp() - interval '${elapsedSince} seconds', win_start = null, win_count = 0 where user_id = '${uid}' and recording_id = '${rec}'`); await as(uid); return rpc(`replay_playback_start('${rec}', ${pos})`); };
  const prog = async (uid, rec) => (await qs(`select * from replay_progress where user_id = '${uid}' and recording_id = '${rec}'`))[0];
  const aged = async (uid, rec) => qs(`update replay_progress set created_at = now() - interval '3 hours' where user_id = '${uid}' and recording_id = '${rec}'`);

  // C0 : ouverture sans lecture
  await as(V3);
  let o = await rpc(`replay_progress_get('${RA.id}')`);
  check('C1 ouverture du replay (progress_get) : aucune couverture, aucune complétion', o.covered_sec === 0 && o.completed === false && o.coverage === 0, JSON.stringify(o));
  o = await rpc(`replay_detail('${RA.id}')`);
  check('C2 ouverture de la fiche (detail) : n\'ouvre aucune session de lecture', o.available === true && (await qs(`select count(*)::int n from replay_progress where user_id = '${V3}' and recording_id = '${RA.id}'`))[0].n === 0);
  await as(V3);
  o = await rpc(`replay_progress_report('${RA.id}', 0, 30, ${ts()})`);
  check('C3 rapport sans lecture signalée (pas de session) : refusé, rien crédité', o.accepted === false && o.reason === 'lecture_non_signalee', JSON.stringify(o));
  o = await start(V3, RA.id, 0, 0);
  check('C4 playback_start : session ouverte, couverture 0', o.ok === true && o.covered_sec === 0 && o.completed === false, JSON.stringify(o));
  await aged(V3, RA.id);
  o = await rep(V3, RA.id, 0, 30, 25);
  check('C5 segment plausible [0,30] en 25 s : accepté', o.accepted === true && o.covered_sec === 30, JSON.stringify(o));
  o = await rep(V3, RA.id, 30, 60, null);
  check('C6 rafale : deuxième rapport immédiat (< cadence minimale) refusé', o.accepted === false && o.reason === 'rafale', JSON.stringify(o));
  o = await rep(V3, RA.id, 300, 330, 25);
  check('C7 saut : segment non contigu refusé (pas de crédit pour un saut du curseur)', o.accepted === false && o.reason === 'saut', JSON.stringify(o));
  o = await rep(V3, RA.id, 30, 60, 5);
  check('C8 double vitesse : 30 s lues en 5 s réelles refusé', o.accepted === false && o.reason === 'vitesse', JSON.stringify(o));
  o = await rep(V3, RA.id, 30, 70, 25);
  check('C9 segment trop long (> 30 s) refusé', o.accepted === false && o.reason === 'segment_trop_long', JSON.stringify(o));
  o = await rep(V3, RA.id, 30, 30, 25);
  check('C10 segment vide / inversé refusé', o.accepted === false && o.reason === 'segment_invalide', JSON.stringify(o));
  const lastTs = (await prog(V3, RA.id)).last_client_ts;
  o = await rep(V3, RA.id, 30, 60, 25, lastTs);
  check('C11 rejeu du même horodatage client refusé', o.accepted === false && o.reason === 'rejeu', JSON.stringify(o));
  o = await rep(V3, RA.id, 30, 60, 25, `(extract(epoch from clock_timestamp()) * 1000)::bigint + 3600000`);
  check('C12 horloge client incohérente refusée', o.accepted === false && o.reason === 'horloge', JSON.stringify(o));
  o = await rep(V3, RA.id, 30, 60, 45);
