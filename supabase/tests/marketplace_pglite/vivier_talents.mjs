let ok = 0, ko = 0;
export async function run(db) {
  const E = '00000000-0000-0000-0000-0000000000e1', X = '00000000-0000-0000-0000-0000000000d1', A = '00000000-0000-0000-0000-0000000000a1', B = '00000000-0000-0000-0000-0000000000b1', C = '00000000-0000-0000-0000-0000000000c1';
  const as = async (uid) => { await db.exec(`reset role; select set_config('request.jwt.claim.sub', '${uid ?? ''}', false); set role authenticated`); };
  const q = async (sql) => (await db.query(sql)).rows;
  const check = (name, cond, extra = '') => { if (cond) { ok++; console.log('OK', name); } else { ko++; console.log('ECHEC', name, extra); } };
  const fails = async (name, sql, re) => { try { await q(sql); check(name, false, 'aurait du echouer'); } catch (e) { check(name, re.test(e.message), e.message); } };
  await db.exec('reset role');
  for (const [id, nm, role] of [[E, 'Orange', 'company'], [X, 'Xena', 'company'], [A, 'Alice', 'student'], [B, 'Bob', 'student'], [C, 'Carl', 'client']]) await db.exec(`insert into auth.users(id,email) values ('${id}','${nm}@t.cm'); insert into profiles(id,name,role,email) values ('${id}','${nm}','${role}','${nm}@t.cm')`);
  await as(E);
  let lists = (await q(`select talent_lists_get() r`))[0].r;
  check('la liste Favoris existe d emblee', lists.length === 1 && lists[0].name === 'Favoris' && lists[0].count === 0, JSON.stringify(lists));
  const fav = lists[0].id;
  const dev = (await q(`select talent_list_create('Developpeurs') r`))[0].r;
  await fails('nom en double refuse', `select talent_list_create('developpeurs')`, /déjà ce nom/);
  await q(`select talent_list_add('${fav}', '${A}', 'Tres bon profil')`);
  await q(`select talent_list_add('${dev}', '${A}')`);
  await q(`select talent_list_add('${dev}', '${B}')`);
  await fails('un client n est pas ajoutable', `select talent_list_add('${dev}', '${C}')`, /Étudiant introuvable/);
  lists = (await q(`select talent_lists_get('${A}') r`))[0].r;
  check('Alice est dans les deux listes', lists.every(l => l.has === true), JSON.stringify(lists));
  lists = (await q(`select talent_lists_get('${B}') r`))[0].r;
  check('Bob seulement dans Developpeurs', lists.find(l => l.name === 'Favoris').has === false && lists.find(l => l.name === 'Developpeurs').has === true);
  const mem = (await q(`select talent_list_members_get('${fav}') r`))[0].r;
  check('membres : nom et note', mem.length === 1 && mem[0].name.startsWith('Alice') && mem[0].note === 'Tres bon profil', JSON.stringify(mem));
  await as(X);
  check('une autre entreprise a ses propres listes, vides', (await q(`select talent_lists_get() r`))[0].r.every(l => l.count === 0));
  await fails('elle ne lit pas la liste d une autre', `select talent_list_members_get('${fav}')`, /Liste introuvable/);
  await fails('elle ne modifie pas la liste d une autre', `select talent_list_add('${fav}', '${B}')`, /Liste introuvable/);
  await as(A);
  await fails('un etudiant n a pas acces', `select talent_lists_get()`, /Réservé aux entreprises/);
  await as(E);
  await q(`select talent_list_remove('${dev}', '${B}')`);
  check('retrait d un etudiant', (await q(`select talent_list_members_get('${dev}') r`))[0].r.length === 1);
  await fails('Favoris ne se supprime pas', `select talent_list_delete('${fav}')`, /Favoris ne peut pas/);
  await q(`select talent_list_delete('${dev}')`);
  check('liste supprimee', (await q(`select talent_lists_get() r`))[0].r.length === 1);
  await db.exec('reset role');
  console.log(`\n${ok}/${ok + ko}`);
}
