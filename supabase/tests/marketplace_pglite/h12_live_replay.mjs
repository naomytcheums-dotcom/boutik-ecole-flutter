  check('B4 anonyme : stockage fermé', (await q(`select count(*)::int n from storage.objects where bucket_id = 'live-replays'`))[0].n === 0);
  await fails('B5 anonyme : replay_play_url refusé', `select replay_play_url('${RA.id}')`, DENY);
  await fails('B6 anonyme : playback/progress refusés', `select replay_playback_start('${RA.id}', 0)`, DENY);
  await fails('B6b anonyme : progress_report / progress_get / quiz / rate / react refusés', `select replay_progress_report('${RA.id}', 0, 5, 1)`, DENY);
