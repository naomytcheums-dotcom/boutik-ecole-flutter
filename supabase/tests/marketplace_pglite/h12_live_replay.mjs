  await sup(); await db.exec(`update live_recording_config set enabled = false`);
  const LS = await mkLive(HOST, 'Live enregistrement en echec', { status: 'live' });
  await sup(); await db.exec(`update live_recording_config set enabled = true`);
  await as(HOST); await rpc(`live_recording_request('${LS}')`);
  const rs = (await qs(`select id from live_recordings where live_id = '${LS}'`))[0].id;
