let ok = 0, ko = 0;
export async function run(db) {
  const E = '00000000-0000-0000-0000-0000000000e1', X = '00000000-0000-0000-0000-0000000000d1', A = '00000000-0000-0000-0000-0000000000a1', B = '00000000-0000-0000-0000-0000000000b1', ADM = '00000000-0000-0000-0000-0000000000ad';
  const N = '00000000-0000-0000-0000-00000000f001';
  const as = async (uid) => { await db.exec(`reset role; select set_config('request.jwt.claim.sub', '${uid ?? ''}', false); set role authenticated`); };
  const q = async (sql) => (await db.query(sql)).rows;
  const check = (name, cond, extra = '') => { if (cond) { ok++; console.log('OK', name); } else { ko++; console.log('ECHEC', name, extra); } };
  const fails = async (name, sql, re) => { try { await q(sql); check(name, false, 'aurait du echouer'); } catch (e) { check(name, re.test(e.message), e.message); } };
  await db.exec('reset role');
  for (const [id, nm, role] of [[E, 'Orange', 'company'], [X, 'Xena', 'company'], [A, 'Alice', 'student'], [B, 'Bob', 'student'], [ADM, 'Admin', 'admin']]) await db.exec(`insert into auth.users(id,email) values ('${id}','${nm}@t.cm'); insert into profiles(id,name,role,email) values ('${id}','${nm}','${role}','${nm}@t.cm')`);
  await db.exec(`insert into contest_announcements (id, poster_id, title, organizer, kind, status, official_url) values ('${N}', '${E}', 'Defi solaire', 'Orange', 'contest', 'pending', 'https://orange.cm/defi')`);
  await as(E);
  await fails('montant trop petit', `select ann_prize_set('${N}', 500)`, /au moins 1 000/);
  check('recompense fixee : en attente de paiement', (await q(`select ann_prize_set('${N}', 100000) r`))[0].r === 'awaiting');
  await as(ADM);
  await fails('publication refusee tant que non payee', `select ann_decide('${N}', true)`, /doit d'abord être payée/);
  await as(E);
  const co = (await q(`select ann_prize_checkout('${N}') r`))[0].r;
  check('paiement demarre avec le montant de la base', co.amount === 100000 && String(co.reference).startsWith('PAY-'), JSON.stringify(co));
  await as(X);
  await fails('une autre entreprise ne peut pas payer ni fixer', `select ann_prize_checkout('${N}')`, /Annonce introuvable/);
  // confirmation du fournisseur (webhook) : sous-payee d abord
  await db.exec(`reset role; update payment_transactions set status = 'confirmed', amount = amount where reference = '${co.reference}'`);
  let st = (await q(`select prize_status, prize_entry from contest_announcements where id = '${N}'`))[0];
  check('paiement confirme : recompense sous sequestre', st.prize_status === 'held' && st.prize_entry, JSON.stringify(st));
  const ent = (await q(`select status, gross, beneficiary_id, platform_amount from money_entries where id = '${st.prize_entry}'`))[0];
  check('ecriture de sequestre retenue', ent.status === 'held' && ent.gross === 100000 && ent.beneficiary_id === null && ent.platform_amount === 100000, JSON.stringify(ent));
  check('le sponsor est prevenu', (await q(`select count(*)::int n from notifications where user_id='${E}' and kind='contest_prize'`))[0].n === 1);
  await as(ADM);
  check('publication possible apres sequestre', (await q(`select ann_decide('${N}', true) r`))[0].r === 'published');
  await as(E);
  await fails('plus de modification apres publication', `select ann_prize_set('${N}', 200000)`, /avant la publication/);
  await fails('gagnant inconnu', `select ann_prize_award('${N}', 'inconnu@t.cm')`, /Aucun compte étudiant/);
  await fails('le sponsor ne se l attribue pas', `select ann_prize_award('${N}', 'Orange@t.cm')`, /Aucun compte étudiant/);
  check('gagnant designe', (await q(`select ann_prize_award('${N}', ' alice@T.cm ') r`))[0].r === 'awarded');
  await db.exec('reset role');
  const ent2 = (await q(`select status, beneficiary_id, beneficiary_amount, platform_amount, split from money_entries where id = '${st.prize_entry}'`))[0];
  check('somme reservee en entier au gagnant, encore sous sequestre', ent2.beneficiary_id === A && ent2.beneficiary_amount === 100000 && ent2.platform_amount === 0 && ent2.status === 'held', JSON.stringify(ent2));
  await as(E);
  await fails('pas de seconde attribution', `select ann_prize_award('${N}', 'bob@t.cm')`, /Aucune récompense en séquestre/);
  await db.exec('reset role');
  check('le gagnant est prevenu', (await q(`select count(*)::int n from notifications where user_id='${A}' and kind='contest_prize'`))[0].n === 1);
  check('l administrateur est prevenu', (await q(`select count(*)::int n from notifications where user_id='${ADM}' and kind='contest_prize'`))[0].n === 1);
  await as(ADM);
  await q(`select money_release_now('${st.prize_entry}')`);
  await db.exec('reset role');
  check('deblocage par l administrateur', (await q(`select status from money_entries where id = '${st.prize_entry}'`))[0].status === 'released');
  const card = (await q(`select ann_my_posted() r`))[0].r;
  await as(E);
  const mine = (await q(`select ann_my_posted() r`))[0].r.find(x => x.id === N);
  check('la carte indique le gagnant', mine.prize_status === 'awarded' && mine.prize_amount === 100000 && String(mine.prize_winner_name).startsWith('Alice'), JSON.stringify(mine));
  // remboursement : une autre annonce sans gagnant
  const M = '00000000-0000-0000-0000-00000000f002';
  await db.exec(`reset role; insert into contest_announcements (id, poster_id, title, organizer, kind, status, official_url) values ('${M}', '${E}', 'Defi sans gagnant', 'Orange', 'contest', 'pending', 'https://orange.cm/defi2')`);
  await as(E);
  await q(`select ann_prize_set('${M}', 50000)`);
  const c2 = (await q(`select ann_prize_checkout('${M}') r`))[0].r;
  await db.exec(`reset role; update payment_transactions set status = 'confirmed' where reference = '${c2.reference}'`);
  await as(E);
  await fails('seul l administrateur rembourse', `select ann_prize_refund('${M}')`, /Réservé à l'administrateur/);
  await as(ADM);
  check('remboursement sans gagnant', (await q(`select ann_prize_refund('${M}', 'Aucun gagnant') r`))[0].r === 'refunded');
  await db.exec('reset role');
  check('ecriture marquee remboursee', (await q(`select status from money_entries where ref = '${c2.reference}'`))[0].status === 'refunded');
  await db.exec('reset role');
  console.log(`\n${ok}/${ok + ko}`);
}
