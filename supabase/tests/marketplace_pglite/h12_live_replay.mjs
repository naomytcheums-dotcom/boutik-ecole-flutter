  await svc(); await fails('A26 type de piste inconnu refusé', `select live_recording_declare_track('${rr}', 'hologramme', 'a/b/c.mp4')`, /inconnu/);
  await srpc(`live_recording_declare_track('${rr}', 'audio', '${HOST}/lr-audio.mp4')`);
