  await sup(); await db.exec(`update live_recording_config set enabled = false`);

  // ============================================================ B. Accès hérité du live et tickets de lecture
  await as(V1);
  let d = await rpc(`replay_play_url('${RA.id}')`);
  check('B1 membre : URL de lecture (ticket de 15 minutes) pour un replay public', d.path === RA.path && d.expires_in === 900 && d.bucket === 'live-replays', JSON.stringify(d));
