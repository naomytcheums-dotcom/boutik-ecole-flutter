let ok = 0, ko = 0;
export async function run(db) {
  const A = '00000000-0000-0000-0000-00000000000a', B = '00000000-0000-0000-0000-00000000000b', C = '00000000-0000-0000-0000-00000000000c', M = '00000000-0000-0000-0000-0000000000ee';
  const as = async (uid, role = 'authenticated') => { await db.exec(`reset role; select set_config('request.jwt.claim.sub', '${uid ?? ''}', false)`); if (role) await db.exec(`set role ${role}`); };
  const q = async (sql) => (await db.query(sql)).rows;
  const check = (name, cond, extra = '') => { if (cond) { ok++; console.log('OK', name); } else { ko++; console.log('ECHEC', name, extra); } };
  const fails = async (name, sql, re) => { try { await q(sql); check(name, false, 'aurait du echouer'); } catch (e) { check(name, re.test(e.message), e.message); } };
  await db.exec('reset role');
  for (const [id, nm, role, dept] of [[A, 'Awa Ancienne', 'student', 'Génie informatique'], [B, 'Paul Etudiant', 'student', 'Génie informatique'], [C, 'Cora Civil', 'student', 'Génie civil'], [M, 'Mod Admin', 'admin', 'Direction']]) {
    await db.exec(`insert into auth.users(id,email) values ('${id}','${nm.split(' ')[0]}@t.cm'); insert into profiles(id,name,role,email,department) values ('${id}','${nm}','${role}','${nm.split(' ')[0]}@t.cm','${dept}')`);
  }
  // --- SOS Cours
  await as(A);
  await fails('SOS : matiere obligatoire', `select sos_create('')`, /matière/);
  const sos = (await q(`select sos_create('TP de reseaux', 'Je bloque sur le routage') id`))[0].id;
  await as(B);
  check('SOS : les etudiants de la filiere sont prevenus', (await q(`select count(*)::int n from notifications where user_id='${B}' and kind='sos'`))[0].n === 1);
  await as(C);
  check('SOS : pas les autres filieres', (await q(`select count(*)::int n from notifications where user_id='${C}' and kind='sos'`))[0].n === 0);
  await as(A);
  await fails('SOS : pas de reponse a son propre SOS', `select sos_answer('${sos}', 'Moi')`, /propre SOS/);
  await as(B);
  check('SOS : liste de ma filiere', (await q(`select sos_list('filiere') r`))[0].r.length === 1);
  const a1 = (await q(`select sos_answer('${sos}', 'Regarde la table de routage statique') id`))[0].id;
  check('SOS : le premier qui repond gagne 15 points', (await q(`select my_points() r`))[0].r.total === 15);
  await as(C);
  await q(`select sos_answer('${sos}', 'Moi aussi je peux aider')`);
  await as(B);
  check('SOS : seul le premier gagne les points de rapidite', (await q(`select my_points() r`))[0].r.total === 15);
  await as(A);
  await fails('SOS : reponse inconnue refusee', `select sos_solve('${sos}', '${sos}')`, /Réponse introuvable/);
  await q(`select sos_solve('${sos}', '${a1}')`);
  check('SOS : resolu, la reponse retenue', (await q(`select sos_list('mine') r`))[0].r[0].status === 'solved');
  await as(B);
  check('SOS : +10 pour la reponse retenue (25 au total)', (await q(`select my_points() r`))[0].r.total === 25);
  // --- défis hebdomadaires
  await as(A);
  await fails('defi : reserve a l equipe', `select challenge_create('Defi Design', 'Refais le logo', 'design', 7)`, /Réservé/);
  await as(M);
  const ch = (await q(`select challenge_create('Defi Design : refais le logo de Boutik-Ecole', 'Une semaine pour proposer', 'design', 7) id`))[0].id;
  await fails('defi : duree 1 a 30 jours', `select challenge_create('Defi', '', 'code', 90)`, /1 à 30/);
  await as(A);
  const eA = (await q(`select challenge_submit('${ch}', 'Mon logo', 'Version orange', 'https://exemple.cm/logo') id`))[0].id;
  await as(B);
  const eB = (await q(`select challenge_submit('${ch}', 'Mon logo bleu') id`))[0].id;
  await fails('defi : pas de vote pour sa propre realisation', `select challenge_vote('${eB}')`, /propre réalisation/);
  await q(`select challenge_vote('${eA}')`);
  await as(C);
  await q(`select challenge_vote('${eA}')`);
  let list = (await q(`select challenges_list() r`))[0].r;
  check('defi : realisations triees par votes', list[0].entries[0].id === eA && list[0].entries[0].votes === 2 && list[0].my_vote === eA && list[0].ended === false);
  await as(null, null);
  await db.exec(`update weekly_challenges set starts_at = now() - interval '8 days', ends_at = now() - interval '1 minute'`);
  await as(C);
  list = (await q(`select challenges_list() r`))[0].r;
  check('defi termine : le plus vote est designe gagnant', list[0].ended === true && list[0].winner_entry === eA && list[0].entries[0].winner === true);
  await fails('defi termine : plus de vote', `select challenge_vote('${eB}')`, /clos/);
  await as(A);
  const mine = (await q(`select my_points() r`))[0].r;
  check('points : 5 (participation) + 50 (victoire) = niveau Bronze', mine.total === 55 && mine.level === 'bronze' && mine.next_at === 150);
  check('classement : le gagnant est premier', (await q(`select top_helpers(5) r`))[0].r[0].user_id === A);
  // --- marché des compétences
  await as(B);
  await fails('competence : echange sans contrepartie refuse', `select skill_post('swap', 'Je t aide en maths')`, /en échange/);
  const sk = (await q(`select skill_post('seek', 'Quelqu un qui sait faire un poster', 'Pour mon projet', 5000) id`))[0].id;
  await q(`select skill_post('swap', 'Je t aide en maths', '', null, 'Aide en anglais')`);
  await as(A);
  await q(`select skill_respond('${sk}', 'Je fais des posters')`);
  await as(B);
  await fails('competence : pas sa propre annonce', `select skill_respond('${sk}')`, /propre annonce/);
  check('competence : l auteur est notifie', (await q(`select count(*)::int n from notifications where user_id='${B}' and kind='skill'`))[0].n === 1);
  const skills = (await q(`select skills_list('seek') r`))[0].r;
  check('competence : annonce avec prix, reponses comptees pour l auteur', skills.length === 1 && skills[0].price === 5000 && skills[0].responses === 1);
  check('competence : reponses lisibles par l auteur', (await q(`select skill_responses_list('${sk}') r`))[0].r[0].message === 'Je fais des posters');
  await as(A);
  await fails('competence : reponses reservees a l auteur', `select skill_responses_list('${sk}')`, /introuvable/);
  await as(B);
  await q(`select skill_close('${sk}')`);
  check('competence : annonce close retiree', (await q(`select skills_list('seek') r`))[0].r.length === 0);
  // --- mur des victoires
  await as(A);
  const v = (await q(`select victory_post('internship', 'J ai eu mon stage chez Orange Cameroun') id`))[0].id;
  await as(B);
  check('victoire : felicitation', (await q(`select victory_cheer('${v}') c`))[0].c === true);
  await as(A);
  check('victoire : l auteur est notifie', (await q(`select count(*)::int n from notifications where user_id='${A}' and kind='victory'`))[0].n === 1);
  await as(B);
  check('victoire : bascule la felicitation', (await q(`select victory_cheer('${v}') c`))[0].c === false);
  await q(`select victory_cheer('${v}')`);
  const vl = (await q(`select victories_list() r`))[0].r;
  check('mur : reussite avec felicitations', vl.length === 1 && vl[0].cheers === 1 && vl[0].cheered === true && vl[0].kind === 'internship');
  await fails('mur : trop court refuse', `select victory_post('other', 'ok')`, /quelques mots/);
  // --- communautés éphémères
  await as(B);
  await fails('ephemere : duree 1 a 14 jours', `select create_ephemeral_community('Revision', '', 40)`, /1 à 14/);
  const e1 = (await q(`select create_ephemeral_community('Revision Examen Reseaux - 15 Nov', 'On revise ensemble', 7) id`))[0].id;
  await q(`select create_ephemeral_community('Eph 2', '', 3)`);
  await q(`select create_ephemeral_community('Eph 3', '', 3)`);
  await fails('ephemere : trois actives au plus', `select create_ephemeral_community('Eph 4', '', 3)`, /Trois communautés éphémères/);
  let cl = await q(`select * from communities_list('Revision Examen')`);
  check('ephemere : publiee tout de suite avec sa date de fin', cl.length === 1 && cl[0].status === 'active' && cl[0].expires_at !== null);
  const vc = (await q(`select victory_post('grade', 'J ai eu 18/20 en reseaux', '${e1}') id`))[0].id;
  await as(C);
  await fails('mur de communaute : reserve aux membres', `select victory_post('grade', 'Intrus dans le mur', '${e1}')`, /Réservé aux membres/);
  await as(null, null);
  await db.exec(`update communities set expires_at = now() - interval '1 minute' where id = '${e1}'`);
  await as(B);
  check('ephemere expiree : masquee de l annuaire', (await q(`select * from communities_list('Revision Examen')`)).length === 0);
  await as(null, null);
  const purged = (await q(`select purge_expired_communities() n`))[0].n;
  check('purge : la communaute expiree est supprimee avec ses reussites', purged === 1 && (await q(`select count(*)::int n from victories where id = '${vc}'`))[0].n === 0);
  console.log(`\n${ok}/${ok + ko}`);
}
